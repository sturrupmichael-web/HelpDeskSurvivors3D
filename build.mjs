// Builds the published index.html: one self-contained page with the CSS and all the
// game's JavaScript (Three.js included) inlined, like the original's build. Edit the code
// under src/, play it with dev.html, then run `npm run build`.

import { build } from 'esbuild';
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';

// Version = time of the last commit in UTC, e.g. 2026.10.25-0412, so the same code always
// gets the same version. Falls back to the build time when git isn't available.
const VERSION = commitTime().toISOString().replace(/^(\d+)-(\d+)-(\d+)T(\d+):(\d+).*/, '$1.$2.$3-$4$5');
const js = await build({
  entryPoints: ['src/main.js'],
  bundle: true,
  format: 'esm',
  target: 'es2022',
  minify: true,
  write: false,
  legalComments: 'none',
  define: { __VERSION__: JSON.stringify(VERSION) },
});
const css = readFileSync('src/ui/style.css', 'utf8');
const html = readFileSync('dev.html', 'utf8')
  .replace(/\s*<script type="importmap">[\s\S]*?<\/script>/, '')
  .replace('<link rel="stylesheet" href="src/ui/style.css">', () => `<style>\n${css}</style>`)
  .replace('<script type="module" src="src/main.js"></script>', () =>
    `<script type="module">\n${js.outputFiles[0].text.replaceAll('</script', '<\\/script')}</script>`,
  )
  .replace('<title>', '<!-- Generated by build.mjs from dev.html and src/. Do not edit by hand. -->\n  <title>');
writeFileSync('index.html', withCsp(html));
console.log(`index.html: ${(html.length / 1024).toFixed(0)} KB, version ${VERSION}`);

// Content Security Policy: the page may only run its own (inline, hashed) scripts and
// talks to nobody. blob: and data: images are for canvas textures.
function withCsp(page) {
  const hashes = [...page.matchAll(/<script(?![^>]*\bsrc=)[^>]*>([\s\S]*?)<\/script>/g)].map(
    (m) => `'sha256-${createHash('sha256').update(m[1]).digest('base64')}'`,
  );
  const csp = [
    "default-src 'self'",
    `script-src 'self' ${hashes.join(' ')}`,
    "style-src 'self' 'unsafe-inline'",
    "img-src 'self' data: blob:",
    "connect-src 'self'",
    "object-src 'none'",
    "base-uri 'none'",
    "form-action 'none'",
  ].join('; ');
  return page.replace('<meta charset="utf-8">', `<meta charset="utf-8">\n  <meta http-equiv="Content-Security-Policy" content="${csp}">`);
}

function commitTime() {
  try {
    return new Date(Number(execFileSync('git', ['log', '-1', '--format=%ct'], { encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).trim()) * 1000);
  } catch {
    return new Date();
  }
}
